// Writes src/senders.generated.ts from the server's bank configuration so the Worker's allow-list
// cannot drift from the parsers. Run with `bun run generate`; a test fails when the file is stale.
import { BANKS } from "../../server/src/parsing/banks-config";

export function render(): string {
  const senders = [...new Set(Object.values(BANKS).flatMap((bank) => bank.senders))].sort();
  return `// Generated by scripts/generate-senders.ts from apps/server/src/parsing/banks-config.ts. Do not edit.
export const BANK_SENDERS: readonly string[] = ${JSON.stringify(senders, null, 2)};
`;
}

if (import.meta.main) {
  await Bun.write(new URL("../src/senders.generated.ts", import.meta.url), render());
}
